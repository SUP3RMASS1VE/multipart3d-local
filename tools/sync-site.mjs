#!/usr/bin/env node
/**
 * Re-mirrors multipart3d.com into ./site and patches it for offline use.
 *
 * Run this again whenever the website is updated (the bundle filenames are
 * content-hashed, so a plain file-by-file refresh would go stale).
 *
 *   node tools/sync-site.mjs
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE = path.join(ROOT, 'site');
const ORIGIN = 'https://www.multipart3d.com';

// drei's built-in "city" environment preset lives on a third-party CDN.
const DREI_HDRI_BASE =
  'https://raw.githack.com/pmndrs/drei-assets/456060a26bbeb8fdf79326f224b6d99b8bcce736/hdri/';
const HDRI_FILES = ['potsdamer_platz_1k.hdr'];

// troika-three-text (used for the 3D labels) resolves fonts through this CDN
// at runtime. Mirror the data it needs so labels render with no internet.
const FONT_CDN =
  'https://cdn.jsdelivr.net/gh/lojjic/unicode-font-resolver@v1.0.1/packages/data';
const FONT_FILES = [
  'codepoint-index/plane0/0-ff.json',
  'font-meta/latin.json',
  // Weights the UI is known to use, plus neighbours in case a style changes.
  ...[100, 200, 300, 400, 500, 600, 700, 800, 900].flatMap((w) => [
    `font-files/latin/sans-serif.normal.${w}.woff`,
    `font-files/latin/sans-serif.italic.${w}.woff`,
  ]),
];

// Files that are referenced from HTML/CSS rather than from the JS bundle.
const ROOT_FILES = [
  'index.html',
  'favicon.ico',
  'favicon-16x16.png',
  'favicon-32x32.png',
  'apple-touch-icon.png',
  'og.png',
  'logo-official.png',
  'robots.txt',
];

let downloaded = 0;
let skipped = 0;

const MESH_HOOK_FROM = 'this.isMesh=!0';
const MESH_HOOK_TO = 'this.isMesh=!0,globalThis.__mp3dMesh||(globalThis.__mp3dMesh=this)';

// Diagnostics only: publishing the camera lets tools project world positions to
// screen coordinates, which is how the profiler finds the cut gizmo to drag.
const CAM_HOOK_FROM = 'this.isPerspectiveCamera=!0';
const CAM_HOOK_TO = 'this.isPerspectiveCamera=!0,globalThis.__mp3dCamera=this';

// Diagnostics only: the scene is the reliable entry point for traversal.
// (__mp3dMesh is whatever Mesh was constructed first, typically an empty
// helper with no position attribute and no parent.)
const SCENE_HOOK_FROM = 'this.isScene=!0';
const SCENE_HOOK_TO = 'this.isScene=!0,globalThis.__mp3dScene=this';
const INSTALL_SNIPPET =
  '\n;import("/mp3d-bvh.js").then(m=>m.install({verbose:false})).catch(e=>console.warn("mp3d-bvh:",e));\n';

/**
 * Suppresses the "Welcome" and "Enjoy your multipart!" dialogs by pre-setting
 * the app's OWN localStorage flags, so it simply believes they were already
 * dismissed. No DOM hacking and no React patching.
 *
 * The flag values are read out of the bundle rather than hardcoded: the intro
 * is gated on a revision string that upstream bumps to re-show it, and a stale
 * hardcoded value would silently let the dialog back in.
 */
async function writePrefsSeed(src) {
  const varOf = (key) => {
    const m = src.match(new RegExp('(\\w+)=`' + key.replace('.', '\\.') + '`'));
    return m ? m[1] : null;
  };

  const introKey = 'm3d.introSeenRevision';
  const thanksKey = 'm3d.thanksHidden';
  const introVar = varOf(introKey);
  const thanksVar = varOf(thanksKey);

  // Intro: openIntroIfUnseen does `getter() !== '<revision>'`
  const introRev = (src.match(/openIntroIfUnseen:\(\)=>\{\w+\(\)!==`([^`]+)`/) || [])[1];
  // Thanks: suppressed when getItem(key) === '<value>'
  const thanksVal = thanksVar
    ? (src.match(new RegExp('getItem\\(' + thanksVar + '\\)===`([^`]+)`')) || [])[1]
    : undefined;

  if (!introVar || !thanksVar || !introRev || !thanksVal) {
    throw new Error(
      'Could not read dialog-suppression flags from the bundle:\n' +
        `  ${introKey} var=${introVar} revision=${introRev}\n` +
        `  ${thanksKey} var=${thanksVar} value=${thanksVal}\n` +
        'The upstream app changed. Re-check tools/sync-site.mjs writePrefsSeed().'
    );
  }

  const contents = `/* Generated by tools/sync-site.mjs - do not edit. */
/* Marks the Welcome and "Enjoy your multipart!" dialogs as already dismissed. */
(function () {
  try {
    localStorage.setItem(${JSON.stringify(introKey)}, ${JSON.stringify(introRev)});
    localStorage.setItem(${JSON.stringify(thanksKey)}, ${JSON.stringify(thanksVal)});
  } catch (e) {
    /* localStorage unavailable: dialogs will simply show as normal. */
  }
})();
`;
  await fs.writeFile(path.join(SITE, 'mp3d-prefs.js'), contents);

  // Must run before the app module. A classic script executes immediately,
  // whereas module scripts are deferred, so head placement is enough.
  const indexPath = path.join(SITE, 'index.html');
  let html = await fs.readFile(indexPath, 'utf8');
  if (!html.includes('mp3d-prefs.js')) {
    html = html.replace('</head>', '    <script src="/mp3d-prefs.js"></script>\n  </head>');
    await fs.writeFile(indexPath, html);
  }

  console.log(`  dialogs suppressed via ${introKey}=${introRev}, ${thanksKey}=${thanksVal}`);
}

// Extra printers to add to the built-in list, keyed on the entry they should
